#!/usr/bin/env python3
"""Relocatable local-process diagnostic. No browser, network, human, or real-product run."""
import argparse
import json
from pathlib import Path
import subprocess
import sys
import tempfile

from fixture import FILES, SKILL, build
from uxresearch.canonical import byte_digest, canonical
from uxresearch.storage import atomic


def run_fixture(root, *, research=False):
    case = build(root)
    research_root, research_baseline = None, None
    if research:
        from research_fixture import attach
        research_root, _ = attach(case, Path(root) / "owned-research", structured=True)
        research_baseline = snapshot(research_root)
    # The packaged launcher is generated by the existing bundle builder.
    launcher = SKILL / "scripts/remorsearch.py"
    prefix = ["personas"]
    if not launcher.is_file():
        launcher, prefix = SKILL / "scripts/ux_personas.py", []
    work = case["work"]
    work.mkdir()  # First-time empty user-selected directory, no permission rewrite.
    baseline = {p.name: byte_digest(p.read_bytes()) for p in case["library"].iterdir()}
    commands = []
    def command(name, *args, expected):
        process = subprocess.run([sys.executable, str(launcher), *prefix, name, "--work", str(work), "--format", "json", *args],
                                 capture_output=True, text=True, timeout=20)
        if process.returncode != expected:
            raise RuntimeError("Diagnostic command failed: " + name + "; " + process.stderr)
        result = json.loads(process.stdout)
        commands.append(dict(command=name, exit_code=process.returncode, expected_exit_code=expected))
        return result
    selection = [item for name in FILES for item in ("--include", name)]
    prepared = command("start", "--source", str(case["source"]), *selection, expected=0)
    assert prepared["execution_performed"] is False
    review = ["--reviewed-research-run", str(research_root)] if research_root else []
    result = command("run", "--library", str(case["library"]), "--input", str(case["plan_path"]), "--allow-reviewed-local-runner", *review, expected=1)
    assert result["counts"]["failed"] == 1 and result["counts"]["inconclusive"] == 1 and result["counts"]["passed"] == 0
    assert result["execution_complete"] and len(result["personas_reused"]) == 2
    assert not result["ui_observed"] and not result["real_user_evidence"] and not result["product_ready"]
    assert command("run", expected=1) == result
    assert command("status", expected=0) == result
    assert baseline == {p.name: byte_digest(p.read_bytes()) for p in case["library"].iterdir()}
    if research_root:
        assert research_baseline == snapshot(research_root)
        assert all(persona["provenance_mode"] == "gated_research" and persona["research"]["export"]["scenario_ids"]
                   for persona in result["personas_reused"])
        assert not any(path.name in {"pages", ".engine", "bundle.json", "gate.json"} for path in work.rglob("*"))
    summary = dict(schema_version="ux-journey-diagnostic.v1", diagnostic_checks_passed=True,
                   product_qa_passed=False, synthetic_known_defect=True, ui_observed=False, real_user_evidence=False,
                   counts=result["counts"], report_path=result["report_path"], commands=commands, launcher=str(launcher.relative_to(SKILL)),
                   personas_reused=result["personas_reused"], original_library_unchanged=True,
                   research_contract="invented_offline_input" if research_root else None,
                   actual_public_acquisition=False, original_research_unchanged=True if research_root else None)
    atomic(Path(root) / "diagnostic.json", canonical(summary))
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return summary


def snapshot(root):
    return {str(path.relative_to(root)): (byte_digest(path.read_bytes()), path.stat().st_mode & 0o777, path.stat().st_mtime_ns)
            for path in root.rglob("*") if path.is_file()}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, help="New directory; keep reports and evidence. An existing directory is refused.")
    parser.add_argument("--research", action="store_true", help="Exercise saved authored research projections using invented offline input, never actual public research")
    args = parser.parse_args()
    if args.out:
        run_fixture(args.out, research=args.research)
    else:
        with tempfile.TemporaryDirectory(prefix="journey-diagnostic-") as temporary:
            run_fixture(Path(temporary).resolve() / "case", research=args.research)
